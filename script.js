// ---------- APPLY TRANSLATION ----------
function applyLanguage(lang) {
  const dict = translations[lang];
  if (!dict) return;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) el.textContent = dict[key];
  });

  const grid = document.getElementById('services-grid');
  grid.innerHTML = '';
  dict.services.forEach((service, i) => {
    const card = document.createElement('div');
    card.className = 'service-card rounded-lg p-4 text-sm font-medium text-[#0a1f44] shadow-sm';
    card.innerHTML = `${serviceIcons[i]}<div>${service}</div>`;
    grid.appendChild(card);
  });

  document.documentElement.setAttribute('dir', lang === 'ur' ? 'rtl' : 'ltr');
}

// ---------- BUILD GALLERY ----------
function buildGallery() {
  const galleryGrid = document.getElementById('gallery-grid');
  galleryGrid.innerHTML = '';
  galleryPhotos.forEach(filename => {
    const img = document.createElement('img');
    img.src = `images/${filename}`;
    img.alt = "Hyderabad Engineering & Fabrication Works project photo";
    img.className = "gallery-img w-full h-40 object-cover rounded-lg shadow-sm cursor-pointer";
    galleryGrid.appendChild(img);
  });
}

// ---------- SCROLL REVEAL ----------
function initScrollReveal() {
  const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add('active');
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.15 });

  document.querySelectorAll('.reveal').forEach(el => observer.observe(el));
}

